import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../../../core/theme/app_theme.dart';
import '../../../../core/utils/file_saver/file_saver.dart';
import '../../../home/presentation/screens/home_screen.dart';
import '../../../workouts/presentation/providers/workout_providers.dart';
import '../../domain/entities/summary_report_entity.dart';

class SummaryReportScreen extends ConsumerStatefulWidget {
  const SummaryReportScreen({super.key});

  @override
  ConsumerState<SummaryReportScreen> createState() =>
      _SummaryReportScreenState();
}

class _SummaryReportScreenState extends ConsumerState<SummaryReportScreen> {
  ReportPeriod _selectedPeriod = ReportPeriod.weekly;
  bool _exportingPdf = false;

  Future<void> _exportPdfReport(SummaryReportEntity report) async {
    setState(() => _exportingPdf = true);
    try {
      final doc = pw.Document();
      final title = _selectedPeriod == ReportPeriod.weekly
          ? 'Weekly Fitness Summary Report'
          : 'Monthly Fitness Summary Report';
      final dateRange =
          '${DateFormat('MMM d').format(report.startDate)} — ${DateFormat('MMM d, yyyy').format(report.endDate)}';

      doc.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return pw.Container(
              padding: const pw.EdgeInsets.all(32),
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  // Title
                  pw.Text('FitX Performance Analytics',
                      style: pw.TextStyle(
                          fontSize: 22, fontWeight: pw.FontWeight.bold)),
                  pw.SizedBox(height: 4),
                  pw.Text(title,
                      style: pw.TextStyle(
                          fontSize: 16, color: PdfColors.grey700)),
                  pw.Text(dateRange,
                      style: pw.TextStyle(
                          fontSize: 12, color: PdfColors.grey600)),
                  pw.Divider(thickness: 1.5),
                  pw.SizedBox(height: 16),

                  // Key Metrics
                  pw.Text('Key Performance Indicators',
                      style: pw.TextStyle(
                          fontSize: 14, fontWeight: pw.FontWeight.bold)),
                  pw.SizedBox(height: 10),
                  pw.Row(
                    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                    children: [
                      _buildPdfStatCard('Workouts', '${report.totalWorkouts}'),
                      _buildPdfStatCard('Total Sets', '${report.totalSets}'),
                      _buildPdfStatCard('Total Volume',
                          '${(report.totalVolumeKg / 1000).toStringAsFixed(1)}k kg'),
                      _buildPdfStatCard(
                          'Consistency', '${report.consistencyScore}%'),
                    ],
                  ),
                  pw.SizedBox(height: 20),

                  // Muscle Distribution
                  pw.Text('Muscle Group Volume Distribution',
                      style: pw.TextStyle(
                          fontSize: 14, fontWeight: pw.FontWeight.bold)),
                  pw.SizedBox(height: 8),
                  if (report.muscleGroupDistribution.isEmpty)
                    pw.Text('No workout data logged in this period.')
                  else
                    ...report.muscleGroupDistribution.entries.map((entry) {
                      final pct = report.totalSets > 0
                          ? ((entry.value / report.totalSets) * 100).toInt()
                          : 0;
                      return pw.Padding(
                        padding: const pw.EdgeInsets.symmetric(vertical: 3),
                        child: pw.Row(
                          mainAxisAlignment:
                              pw.MainAxisAlignment.spaceBetween,
                          children: [
                            pw.Text(entry.key,
                                style: const pw.TextStyle(fontSize: 12)),
                            pw.Text('${entry.value} sets ($pct%)',
                                style: pw.TextStyle(
                                    fontSize: 12,
                                    fontWeight: pw.FontWeight.bold)),
                          ],
                        ),
                      );
                    }),

                  pw.SizedBox(height: 30),
                  pw.Divider(thickness: 0.5),
                  pw.Center(
                    child: pw.Text(
                      'Generated by FitX — Your AI Gym & Fitness Partner',
                      style: const pw.TextStyle(
                          fontSize: 10, color: PdfColors.grey500),
                    ),
                  ),
                ],
              ),
            );
          },
        ),
      );

      final pdfBytes = await doc.save();
      final fileName =
          'fitx_summary_${DateFormat('yyyyMMdd').format(DateTime.now())}.pdf';

      await saveAndShareFile(
        bytes: pdfBytes,
        fileName: fileName,
        mimeType: 'application/pdf',
        shareText: 'My FitX $title',
        shareSubject: 'FitX Performance Report',
      );

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Report exported successfully! 📄'),
            backgroundColor: AppTheme.primaryGreen,
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to export PDF: $e'),
            backgroundColor: AppTheme.errorRed,
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _exportingPdf = false);
    }
  }

  pw.Widget _buildPdfStatCard(String label, String value) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(6)),
      ),
      child: pw.Column(
        children: [
          pw.Text(value,
              style:
                  pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 2),
          pw.Text(label,
              style:
                  const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final workoutsAsync = ref.watch(workoutsProvider);
    final streakAsync = ref.watch(streakProvider);
    final prsAsync = ref.watch(personalRecordsProvider);
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    return Scaffold(
      appBar: AppBar(
        title: const Text('Performance Report 📊'),
      ),
      body: workoutsAsync.when(
        loading: () =>
            const Center(child: CircularProgressIndicator.adaptive()),
        error: (err, _) => Center(child: Text('Error: $err')),
        data: (workouts) {
          final streak = streakAsync.valueOrNull ?? 0;
          final prs = prsAsync.valueOrNull ?? [];
          final report = SummaryReportEntity.generate(
            period: _selectedPeriod,
            allWorkouts: workouts,
            prsCount: prs.length,
            streakDays: streak,
          );

          final dateStr =
              '${DateFormat('MMM d').format(report.startDate)} — ${DateFormat('MMM d, yyyy').format(report.endDate)}';

          return ListView(
            padding: const EdgeInsets.all(16),
            children: [
              // Period Selector
              Center(
                child: SegmentedButton<ReportPeriod>(
                  segments: const [
                    ButtonSegment(
                      value: ReportPeriod.weekly,
                      label: Text('Weekly Summary'),
                    ),
                    ButtonSegment(
                      value: ReportPeriod.monthly,
                      label: Text('Monthly Summary'),
                    ),
                  ],
                  selected: {_selectedPeriod},
                  onSelectionChanged: (set) =>
                      setState(() => _selectedPeriod = set.first),
                ),
              ),
              const SizedBox(height: 16),

              // Hero Score Card
              Container(
                padding: const EdgeInsets.all(20),
                decoration: BoxDecoration(
                  gradient: const LinearGradient(
                    colors: [Colors.deepPurple, AppTheme.secondaryBlue],
                    begin: Alignment.topLeft,
                    end: Alignment.bottomRight,
                  ),
                  borderRadius: BorderRadius.circular(20),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Text(
                          dateStr,
                          style: const TextStyle(
                            color: Colors.white70,
                            fontSize: 12,
                            fontWeight: FontWeight.w600,
                          ),
                        ),
                        Container(
                          padding: const EdgeInsets.symmetric(
                              horizontal: 8, vertical: 3),
                          decoration: BoxDecoration(
                            color: Colors.white.withValues(alpha: 0.2),
                            borderRadius: BorderRadius.circular(8),
                          ),
                          child: Text(
                            'Score: ${report.consistencyScore}/100',
                            style: const TextStyle(
                              color: Colors.white,
                              fontSize: 11,
                              fontWeight: FontWeight.bold,
                            ),
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),
                    Row(
                      children: [
                        Container(
                          width: 54,
                          height: 54,
                          alignment: Alignment.center,
                          decoration: BoxDecoration(
                            shape: BoxShape.circle,
                            color: Colors.white.withValues(alpha: 0.2),
                          ),
                          child: const Text('🔥',
                              style: TextStyle(fontSize: 26)),
                        ),
                        const SizedBox(width: 14),
                        Expanded(
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Text(
                                '${report.totalWorkouts} Workouts Completed',
                                style: const TextStyle(
                                  color: Colors.white,
                                  fontSize: 18,
                                  fontWeight: FontWeight.bold,
                                ),
                              ),
                              const SizedBox(height: 2),
                              Text(
                                report.volumeChangePct >= 0
                                    ? '📈 +${report.volumeChangePct.toStringAsFixed(1)}% volume vs prior period'
                                    : '📉 ${report.volumeChangePct.toStringAsFixed(1)}% volume vs prior period',
                                style: const TextStyle(
                                  color: Colors.white70,
                                  fontSize: 12,
                                ),
                              ),
                            ],
                          ),
                        ),
                      ],
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 16),

              // 4 KPI Grid
              Row(
                children: [
                  Expanded(
                    child: _KpiCard(
                      label: 'Total Volume',
                      value:
                          '${(report.totalVolumeKg / 1000).toStringAsFixed(1)}k kg',
                      icon: Icons.fitness_center_rounded,
                      color: AppTheme.primaryGreen,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: _KpiCard(
                      label: 'Total Sets',
                      value: '${report.totalSets}',
                      icon: Icons.layers_outlined,
                      color: AppTheme.secondaryBlue,
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 12),
              Row(
                children: [
                  Expanded(
                    child: _KpiCard(
                      label: 'Avg Duration',
                      value: '${report.avgDurationMinutes} min',
                      icon: Icons.timer_outlined,
                      color: AppTheme.accentOrange,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: _KpiCard(
                      label: 'Top Focus',
                      value: report.topMuscleGroup,
                      icon: Icons.accessibility_new_rounded,
                      color: Colors.deepPurple,
                    ),
                  ),
                ],
              ),
              const SizedBox(height: 20),

              // Muscle Group Breakdown
              const Text(
                'Muscle Group Volume Distribution',
                style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 10),
              if (report.muscleGroupDistribution.isEmpty)
                Card(
                  child: Padding(
                    padding: const EdgeInsets.all(16),
                    child: Center(
                      child: Text(
                        'No workout sets logged in this ${_selectedPeriod == ReportPeriod.weekly ? 'week' : 'month'}.',
                        style: TextStyle(color: Colors.grey.shade600),
                      ),
                    ),
                  ),
                )
              else
                Card(
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(16),
                  ),
                  child: Padding(
                    padding: const EdgeInsets.all(16),
                    child: Column(
                      children:
                          report.muscleGroupDistribution.entries.map((entry) {
                        final pct = report.totalSets > 0
                            ? entry.value / report.totalSets
                            : 0.0;
                        return Padding(
                          padding: const EdgeInsets.only(bottom: 12),
                          child: Column(
                            crossAxisAlignment: CrossAxisAlignment.start,
                            children: [
                              Row(
                                mainAxisAlignment:
                                    MainAxisAlignment.spaceBetween,
                                children: [
                                  Text(
                                    entry.key,
                                    style: const TextStyle(
                                      fontWeight: FontWeight.w600,
                                      fontSize: 13,
                                    ),
                                  ),
                                  Text(
                                    '${entry.value} sets (${(pct * 100).toInt()}%)',
                                    style: TextStyle(
                                      fontSize: 12,
                                      color: Colors.grey.shade600,
                                    ),
                                  ),
                                ],
                              ),
                              const SizedBox(height: 6),
                              ClipRRect(
                                borderRadius: BorderRadius.circular(4),
                                child: LinearProgressIndicator(
                                  value: pct,
                                  minHeight: 6,
                                  backgroundColor: isDark
                                      ? const Color(0xFF2A2A2A)
                                      : Colors.grey.shade200,
                                  valueColor: const AlwaysStoppedAnimation<Color>(
                                      AppTheme.primaryGreen),
                                ),
                              ),
                            ],
                          ),
                        );
                      }).toList(),
                    ),
                  ),
                ),
              const SizedBox(height: 24),

              // Export PDF button
              ElevatedButton.icon(
                onPressed:
                    _exportingPdf ? null : () => _exportPdfReport(report),
                icon: _exportingPdf
                    ? const SizedBox(
                        width: 18,
                        height: 18,
                        child: CircularProgressIndicator(
                            strokeWidth: 2, color: Colors.white),
                      )
                    : const Icon(Icons.picture_as_pdf_outlined),
                label: Text(_exportingPdf
                    ? 'Generating PDF…'
                    : 'Export & Share PDF Report'),
                style: ElevatedButton.styleFrom(
                  padding: const EdgeInsets.symmetric(vertical: 14),
                ),
              ),
            ],
          );
        },
      ),
    );
  }
}

class _KpiCard extends StatelessWidget {
  final String label;
  final String value;
  final IconData icon;
  final Color color;

  const _KpiCard({
    required this.label,
    required this.value,
    required this.icon,
    required this.color,
  });

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    return Container(
      padding: const EdgeInsets.all(14),
      decoration: BoxDecoration(
        color: isDark ? const Color(0xFF252525) : Colors.grey.shade50,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(
          color: isDark ? const Color(0xFF333333) : Colors.grey.shade200,
        ),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Container(
            width: 32,
            height: 32,
            alignment: Alignment.center,
            decoration: BoxDecoration(
              color: color.withValues(alpha: 0.15),
              borderRadius: BorderRadius.circular(8),
            ),
            child: Icon(icon, size: 18, color: color),
          ),
          const SizedBox(height: 10),
          Text(
            value,
            style: const TextStyle(
              fontWeight: FontWeight.bold,
              fontSize: 16,
            ),
          ),
          const SizedBox(height: 2),
          Text(
            label,
            style: TextStyle(
              fontSize: 11,
              color: Colors.grey.shade600,
            ),
          ),
        ],
      ),
    );
  }
}
